"""Loudness of the narration, one value (0..1) per video frame -> demo-project/src/<slug>/voiceenv.ts
(drives the mouth-flap effect `talk:` in Fx.tsx so the mouth opens exactly when the voice is loud).

usage: python scripts/voice_env.py --slug zs-ep01 [--fps 30]
"""
import argparse
import os
import wave

import numpy as np


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--slug", required=True)
    ap.add_argument("--fps", type=int, default=30)
    a = ap.parse_args()
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    src = os.path.join(root, "demo-project", "public", a.slug, "voice.wav")
    with wave.open(src, "rb") as w:
        sr, n, ch = w.getframerate(), w.getnframes(), w.getnchannels()
        x = np.frombuffer(w.readframes(n), dtype=np.int16).astype(np.float64) / 32768.0
    if ch > 1:
        x = x.reshape(-1, ch).mean(axis=1)
    hop = sr // a.fps
    frames = len(x) // hop
    rms = np.sqrt(np.mean(x[: frames * hop].reshape(frames, hop) ** 2, axis=1))
    rms = rms / (np.percentile(rms, 97) or 1)
    rms = np.clip(rms, 0, 1) ** 0.7
    sm = np.convolve(rms, np.array([0.25, 0.5, 0.25]), mode="same")
    sm[sm < 0.08] = 0
    out = os.path.join(root, "demo-project", "src", a.slug, "voiceenv.ts")
    with open(out, "w", encoding="utf-8") as f:
        f.write("// Generated by scripts/voice_env.py: voice loudness per frame (0..1). Re-run after gen_voice.py.\n")
        f.write("export const VOICE_ENV: number[] = [" + ",".join(f"{v:.2f}".rstrip("0").rstrip(".") if v else "0" for v in sm) + "];\n")
    print(frames, "frames ->", out)


if __name__ == "__main__":
    main()
