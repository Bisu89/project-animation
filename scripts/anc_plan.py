#!/usr/bin/env python3
"""Turn an episode's visual plan into scene files.

  python scripts/anc_plan.py --slug anc-ep01

Reads   content/<slug>/plan.py        (P = {scene: visual}, TARGET, MIN_S: see content/anc-ep01/plan.py)
Needs   demo-project/src/<slug>/timeline.json   (from gen_voice.py)
Writes  content/<slug>/prompts.txt, content/<slug>/scenes.csv   (one row per scene; only rows with a prompt need a picture)
        demo-project/src/<slug>/scenes.ts, visuals.ts
Run this instead of build_scenes.py alone: build_scenes would put prompts back on the reused/animated/diagram scenes.
If the script changes, re-run gen_voice.py first, then this, then re-check plan.py (scene numbers shift).
"""
import argparse, csv, importlib.util, json, os, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--slug", required=True)
    ap.add_argument("--style-file", default="content/anc-style.txt")
    a = ap.parse_args()
    spec = importlib.util.spec_from_file_location("plan", os.path.join(ROOT, "content", a.slug, "plan.py"))
    plan = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(plan)
    P, target, min_s = plan.P, getattr(plan, "TARGET", 10), getattr(plan, "MIN_S", 5)

    def build():
        subprocess.check_call([sys.executable, os.path.join(ROOT, "scripts", "build_scenes.py"), "--slug", a.slug, "--target", str(target), "--min-s", str(min_s), "--style-file", a.style_file], stdout=subprocess.DEVNULL)

    # first pass: learn how many scenes the voice timeline gives
    prompts = os.path.join(ROOT, "content", a.slug, "prompts.txt")
    open(prompts, "w", encoding="utf-8").write("")
    build()
    n_scenes = len(list(csv.reader(open(os.path.join(ROOT, "content", a.slug, "scenes.csv"), encoding="utf-8")))) - 1
    missing = [n for n in range(1, n_scenes + 1) if n not in P]
    extra = [n for n in P if n > n_scenes or n < 1]
    if missing or extra:
        sys.exit(f"plan.py does not match the {n_scenes} scenes: missing {missing}, unknown {extra}")
    lines = []
    for n in range(1, n_scenes + 1):
        v = P[n]
        lines.append(f"{v[1]} | {v[2]}" if v[0] == "img" else f"mo:in | (no picture needed: {v[0]} {v[1:]})")
    open(prompts, "w", encoding="utf-8").write("\n".join(lines) + "\n")
    build()
    p = os.path.join(ROOT, "content", a.slug, "scenes.csv")
    rows = list(csv.reader(open(p, encoding="utf-8")))
    h = rows[0]
    ii, ip = h.index("image_filename"), h.index("image_prompt")
    vis = {}
    for r in rows[1:]:
        n = int(r[0])
        v = P[n]
        if v[0] == "img":
            vis[n] = {"kind": "img", "file": r[ii]}
            continue
        r[ip] = ""
        if v[0] == "pilot":
            r[ii] = f"(reuse pilot picture {v[1]})"
            vis[n] = {"kind": "img", "file": f"pilot_{v[1]:02d}.png"}
        elif v[0] == "same":
            r[ii] = f"(same picture as scene {v[1]})"
            vis[n] = {"kind": "same", "of": v[1]}
        elif v[0] == "act":
            r[ii] = f"(animated: {v[1]})"
            vis[n] = {"kind": "act", "key": v[1]}
        else:
            r[ii] = f"(diagram {v[1]} stage {v[2]})"
            vis[n] = {"kind": "diag", "key": v[1], "stage": v[2]}
    for k, v in list(vis.items()):
        if v["kind"] == "same":
            vis[k] = {**vis[v["of"]], "same": v["of"]}
    csv.writer(open(p, "w", encoding="utf-8", newline="")).writerows(rows)
    ts = os.path.join(ROOT, "demo-project", "src", a.slug, "visuals.ts")
    with open(ts, "w", encoding="utf-8") as f:
        f.write("// Generated by scripts/anc_plan.py. What each scene shows.\n")
        f.write('export type Visual = ({ kind: "img"; file: string } | { kind: "act"; key: string } | { kind: "diag"; key: string; stage: number }) & { same?: number };\n')
        f.write("export const VISUALS: Record<number, Visual> = " + json.dumps(vis, indent=1) + ";\n")
    kinds = [v[0] for v in P.values()]
    print(json.dumps({"scenes": n_scenes, **{k: kinds.count(k) for k in ("img", "pilot", "same", "act", "diag")}}))


if __name__ == "__main__":
    main()
